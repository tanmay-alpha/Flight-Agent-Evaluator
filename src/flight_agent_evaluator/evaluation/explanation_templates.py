def template_id_for_code(code_value: str) -> str:
    """Return the default template ID for a failure code string value."""
    return _CODE_TO_TEMPLATE.get(code_value, "tmpl-unknown-unclassified-v1")


def render_explanation(template_id: str, context: dict[str, Any]) -> str:
    """Render a named explanation template with *context* values.

    All interpolation values must be derivable from :class:`FailureEvidence`
    or :class:`FailureInstance` fields.  Unknown template IDs fall back to
    the unclassified template.  Missing context keys are substituted with
    ``'<unknown>'`` to avoid ``KeyError``.
    """
    template = EXPLANATION_TEMPLATES.get(
        template_id,
        EXPLANATION_TEMPLATES["tmpl-unknown-unclassified-v1"],
    )
    # Safe substitution: replace missing keys with '<unknown>'
    import string

    formatter = string.Formatter()
    result_parts: list[str] = []
    for literal_text, field_name, format_spec, conversion in formatter.parse(template):
        result_parts.append(literal_text)
        if field_name is not None:
            value = context.get(field_name, "<unknown>")
            if conversion == "r":
                value = repr(value)
            elif conversion == "s":
                value = str(value)
            if format_spec:
                try:
                    value = format(value, format_spec)
                except (ValueError, TypeError):
                    value = str(value)
            result_parts.append(str(value))
    return "".join(result_parts)
