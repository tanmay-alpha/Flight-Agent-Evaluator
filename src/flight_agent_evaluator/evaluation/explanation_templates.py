"""Versioned deterministic explanation templates for failure instances.

Gate 11 of the Stage 3 diagnostic validity specification.

Every explanation template produces a factual sentence by interpolating
evidence-backed values.  Templates must never be generated by an LLM.

Template naming convention:
    tmpl-<domain>-<failure-description>-v<version>

Adding a template does not require a taxonomy version bump.
Changing template semantics in a way that alters factual content does.
"""

