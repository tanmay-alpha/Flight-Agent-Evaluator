_SCENARIO_ID = "challenge-scenario-001"
_RUN_ID = str(uuid.uuid4())
_PATH_ID = "path_direct"


def _make_expectation(
    actions: list[ExpectedAction] | None = None,
    forbidden: list[ForbiddenActionConstraint] | None = None,
    precedence: list[PrecedenceConstraint] | None = None,
    recovery: list[RecoveryConstraint] | None = None,
) -> TrajectoryExpectation:
    if actions is None:
        actions = [
            ExpectedAction(
                node_id="search_flights",
                selector=ActionSelector(tool_name="flight.search"),
                required=True,
            ),
            ExpectedAction(
                node_id="get_details",
                selector=ActionSelector(tool_name="flight.get_details"),
                required=True,
            ),
        ]
    path = ValidPath(
        path_id=_PATH_ID,
        expected_actions=actions,
        forbidden_actions=forbidden or [],
        precedence_constraints=precedence or [],
        recovery_constraints=recovery or [],
    )
    return TrajectoryExpectation(scenario_id=_SCENARIO_ID, valid_paths=[path])


def _make_scorecard(
    overall_pass: bool = False,
    outcome_score: float = 1.0,
    ordering_score: float = 1.0,
    dependency_score: float = 1.0,
    efficiency_score: float = 1.0,
    required_recall: float = 1.0,
    safety_pass: bool = True,
    safety_violations: list[str] | None = None,
    evaluator_error: str | None = None,
    attribution: list[EvidenceAttribution] | None = None,
) -> TrajectoryScorecard:
    return TrajectoryScorecard(
        scenario_id=_SCENARIO_ID,
        run_id=_RUN_ID,
        selected_path_id=_PATH_ID,
        overall_pass=overall_pass,
        evaluator_error=evaluator_error,
        outcome_score=outcome_score,
        tool_precision=1.0,
        required_recall=required_recall,
        tool_f1=1.0,
        argument_correctness_score=1.0,
        dependency_score=dependency_score,
        ordering_score=ordering_score,
        efficiency_score=efficiency_score,
        recovery_score=1.0,
        composite_score=1.0 if overall_pass else 0.0,
        safety_pass=safety_pass,
        safety_violations=safety_violations or [],
        evidence_attribution=attribution or [],
    )


def _add_entry(journal: HashChainJournal, entry_type: str, payload: dict[str, object]) -> None:
    prev_hash = journal.entries[-1].hash if journal.entries else ""
    seq = len(journal.entries) + 1
    raw = JournalEntry(
        id=uuid.uuid4(),
        run_id=_RUN_ID,
        correlation_id=str(uuid.uuid4()),
        seq=seq,
        time="2026-08-09T12:00:00Z",
        prev_hash=prev_hash,
        hash="",
        type=entry_type,
        payload=payload,
    )
    journal.append(raw)


