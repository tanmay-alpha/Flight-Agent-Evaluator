class TestChallengeSet:
    """Run all 32 challenge cases through the diagnostic engine and compute metrics."""

    def test_challenge_set_execution_and_metrics(self):
        engine = FailureDiagnosticEngine()
        labels: list[ChallengeLabel] = []
        results: list[ChallengeResult] = []

        for lbl, sc, exp, j in CHALLENGE_CASES:
            labels.append(lbl)
            report = engine.diagnose_report(sc, exp, j)

            # Extract primary prediction
            primary_code = report.failures[0].failure_code if report.failures else None
            secondary_codes = tuple(f.failure_code for f in report.failures[1:])
            origin = report.failures[0].origin if report.failures else None
            severity = report.failures[0].severity if report.failures else None
            crit_seq = report.critical_steps[0].journal_sequence if report.critical_steps else None

            results.append(
                ChallengeResult(
                    case_id=lbl.case_id,
                    predicted_primary_code=primary_code,
                    predicted_secondary_codes=secondary_codes,
                    predicted_origin=origin,
                    predicted_severity=severity,
                    critical_step_sequence=crit_seq,
                )
            )

            # Contract checks on each report
            assert report.taxonomy_version == "failure-taxonomy-v1"
            assert report.diagnostic_status in (
                DiagnosticStatus.COMPLETE,
                DiagnosticStatus.PARTIAL,
                DiagnosticStatus.EVALUATOR_ERROR,
                DiagnosticStatus.INSUFFICIENT_EVIDENCE,
            )
            assert report.evidence_graph.is_consistent()

        metrics = compute_diagnostic_metrics(labels, results)

        assert metrics.n_cases == len(CHALLENGE_CASES)
        assert metrics.n_cases >= 30
        assert metrics.primary_label_accuracy >= 0.85
        assert metrics.origin_accuracy >= 0.85
        assert metrics.unclassified_rate == 0.0

    def test_explanation_formatting_no_placeholders(self):
        engine = FailureDiagnosticEngine()
        for _, sc, exp, j in CHALLENGE_CASES:
            report = engine.diagnose_report(sc, exp, j)
            for f in report.failures:
                if f.directly_observed and f.first_observed_sequence is not None and f.tool_call_ids:
                    assert "<unknown>" not in f.explanation
